<?php
/**
 * Preset Generator for robots.txt configurations.
 *
 * @package WPCalibrate\RobotsRepair
 */

declare(strict_types=1);

namespace WPCalibrate\RobotsRepair\Repair;

use WPCalibrate\RobotsRepair\Diagnostics\SitemapChecker;
use WPCalibrate\RobotsRepair\Diagnostics\WooCommerceChecker;

// Exit if accessed directly.
if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

/**
 * Class PresetFactory
 *
 * Generates conservative, search-engine compliant preset rule templates.
 */
final class PresetFactory {

	public const PRESET_RECOMMENDED = 'recommended';
	public const PRESET_WOOCOMMERCE  = 'woocommerce';
	public const PRESET_CUSTOM       = 'custom';

	/**
	 * Generate rules for the specified preset mode.
	 *
	 * @param string      $mode Preset mode ('recommended', 'woocommerce', 'custom').
	 * @param string|null $sitemap_url Optional specific sitemap URL.
	 * @return string Generated robots.txt content.
	 */
	public static function generate( string $mode, ?string $sitemap_url = null ): string {
		$target_sitemap = $sitemap_url;
		if ( null === $target_sitemap ) {
			$sm_report      = SitemapChecker::check_sitemaps();
			$target_sitemap = $sm_report['primary_sitemap'];
		}

		if ( self::PRESET_WOOCOMMERCE === $mode && WooCommerceChecker::is_active() ) {
			return self::generate_woocommerce_preset( $target_sitemap );
		}

		return self::generate_recommended_preset( $target_sitemap );
	}

	/**
	 * Generate standard Recommended WordPress preset.
	 *
	 * Conservative rules allowing search engines full access to frontend assets,
	 * while disallowing admin backend and allowing admin-ajax.php.
	 *
	 * @param string|null $sitemap_url Verified sitemap URL.
	 * @return string
	 */
	public static function generate_recommended_preset( ?string $sitemap_url = null ): string {
		$lines = [
			'# Standard WordPress crawl rules generated by WPCalibrate Robots Repair',
			'User-agent: *',
			'Disallow: /wp-admin/',
			'Allow: /wp-admin/admin-ajax.php',
		];

		if ( ! empty( $sitemap_url ) ) {
			$lines[] = '';
			$lines[] = 'Sitemap: ' . esc_url_raw( $sitemap_url );
		}

		return implode( "\n", $lines ) . "\n";
	}

	/**
	 * Generate WooCommerce-optimized preset.
	 *
	 * Protects dynamic customer cart, checkout, and account endpoints from crawler bloat,
	 * without blocking shop catalog, product pages, product tags, or images.
	 *
	 * @param string|null $sitemap_url Verified sitemap URL.
	 * @return string
	 */
	public static function generate_woocommerce_preset( ?string $sitemap_url = null ): string {
		$lines = [
			'# WooCommerce crawl rules generated by WPCalibrate Robots Repair',
			'User-agent: *',
			'Disallow: /wp-admin/',
			'Allow: /wp-admin/admin-ajax.php',
		];

		$transactional = WooCommerceChecker::get_transactional_rules();
		if ( ! empty( $transactional ) ) {
			$lines[] = '';
			$lines[] = '# Non-indexable WooCommerce customer endpoints';
			foreach ( $transactional as $rule ) {
				$lines[] = 'Disallow: ' . $rule['path'];
			}
		}

		if ( ! empty( $sitemap_url ) ) {
			$lines[] = '';
			$lines[] = 'Sitemap: ' . esc_url_raw( $sitemap_url );
		}

		return implode( "\n", $lines ) . "\n";
	}
}
