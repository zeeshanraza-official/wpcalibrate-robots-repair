/**
 * Class SourceDetector
 *
 * Discovers and attributes the true source generating the public robots.txt:
 * Physical file, WordPress Virtual, WPCalibrate, SEO plugin, or CDN/Cache layer.
 */
final class SourceDetector {

	public const SOURCE_PHYSICAL   = 'physical';
	public const SOURCE_PLUGIN     = 'plugin_virtual';
	public const SOURCE_WP_VIRTUAL = 'wp_virtual';
	public const SOURCE_SEO_PLUGIN = 'seo_plugin';
	public const SOURCE_CDN_SERVER = 'cdn_server';
	public const SOURCE_UNKNOWN    = 'unknown';

	/**
	 * Determine source using evidence-based inspection.
	 *
	 * @param array<string, mixed> $physical_info Physical file inspection.
	 * @param array<string, mixed> $public_info Public HTTP fetch inspection.
	 * @param array<string, mixed> $seo_info SEO plugins inspection.
	 * @param string               $plugin_virtual_content Stored plugin virtual rules.
	 * @return array<string, mixed>
	 */
	public static function determine_source(
		array $physical_info,
		array $public_info,
		array $seo_info,
		string $plugin_virtual_content = ''
	): array {
		$public_content = trim( (string) ( $public_info['content'] ?? '' ) );
		$public_norm    = self::normalize( $public_content );
		$cdn_headers    = self::detect_cdn_headers( $public_info['headers'] ?? [] );

		// Case 1: Physical file exists.
		if ( ! empty( $physical_info['exists'] ) ) {
			$physical_content = trim( (string) ( $physical_info['content'] ?? '' ) );
			$physical_norm    = self::normalize( $physical_content );

			if ( '' !== $public_norm && $public_norm === $physical_norm ) {
				return [
					'source_type' => self::SOURCE_PHYSICAL,
					'label'       => __( 'Physical File in Web Root', 'wpcalibrate-robots-repair' ),
					'evidence'    => __( 'Public HTTP response exactly matches the physical robots.txt file in the site root directory.', 'wpcalibrate-robots-repair' ),
					'takes_precedence' => true,
					'cdn_detected'     => ! empty( $cdn_headers ),
					'cdn_details'      => $cdn_headers,
				];
			}

			// Physical file exists, but public response is different!
			return [
				'source_type' => self::SOURCE_CDN_SERVER,
				'label'       => __( 'Server / CDN / Cache Conflict', 'wpcalibrate-robots-repair' ),
				'evidence'    => __( 'A physical robots.txt file exists on the server, but the public HTTP response differs. An external cache, CDN, or server rewrite may be overriding the file.', 'wpcalibrate-robots-repair' ),
				'takes_precedence' => true,
				'cdn_detected'     => ! empty( $cdn_headers ),
				'cdn_details'      => $cdn_headers,
			];
		}

		// Case 2: No physical file exists. Public content is served virtually.
		if ( '' !== $plugin_virtual_content ) {
			$plugin_norm = self::normalize( $plugin_virtual_content );
			if ( '' !== $public_norm && $public_norm === $plugin_norm ) {
				return [
					'source_type' => self::SOURCE_PLUGIN,
					'label'       => __( 'WPCalibrate Virtual Configuration', 'wpcalibrate-robots-repair' ),
					'evidence'    => __( 'Public HTTP response matches the virtual rules generated by WPCalibrate Robots Repair.', 'wpcalibrate-robots-repair' ),
					'takes_precedence' => false,
					'cdn_detected'     => ! empty( $cdn_headers ),
					'cdn_details'      => $cdn_headers,
				];
			}
		}

		// Check if an SEO plugin's filter is dominating.
		if ( ! empty( $seo_info['has_filter_conflict'] ) ) {
			return [
				'source_type' => self::SOURCE_SEO_PLUGIN,
				'label'       => __( 'Third-Party SEO Plugin Filter', 'wpcalibrate-robots-repair' ),
				'evidence'    => sprintf(
					/* translators: %s: filter count */
					__( 'WordPress virtual output is actively modified by third-party plugin filters on robots_txt hook (%d active).', 'wpcalibrate-robots-repair' ),
					count( $seo_info['third_party_filters'] )
				),
				'takes_precedence' => false,
				'cdn_detected'     => ! empty( $cdn_headers ),
				'cdn_details'      => $cdn_headers,
			];
		}

		// Core virtual output comparison.
		$core_virtual = self::generate_core_virtual_sample();
		if ( '' !== $public_norm && $public_norm === self::normalize( $core_virtual ) ) {
			return [
				'source_type' => self::SOURCE_WP_VIRTUAL,
				'label'       => __( 'WordPress Core Virtual robots.txt', 'wpcalibrate-robots-repair' ),
				'evidence'    => __( 'Public HTTP response matches default WordPress core virtual output.', 'wpcalibrate-robots-repair' ),
				'takes_precedence' => false,
				'cdn_detected'     => ! empty( $cdn_headers ),
				'cdn_details'      => $cdn_headers,
			];
		}

		// Fallback: Unknown or External.
		return [
			'source_type' => self::SOURCE_UNKNOWN,
			'label'       => __( 'Dynamic / External Source', 'wpcalibrate-robots-repair' ),
			'evidence'    => __( 'Public response does not match local files or standard WordPress virtual presets.', 'wpcalibrate-robots-repair' ),
			'takes_precedence' => false,
			'cdn_detected'     => ! empty( $cdn_headers ),
			'cdn_details'      => $cdn_headers,
		];
	}

	/**
	 * Inspect headers for common CDN and caching layers.
	 *
	 * @param array<string, mixed> $headers
	 * @return array<string, string>
	 */
	public static function detect_cdn_headers( array $headers ): array {
		$detected = [];
		$flat     = [];

		foreach ( $headers as $k => $v ) {
			$flat[ strtolower( (string) $k ) ] = is_array( $v ) ? implode( ', ', $v ) : (string) $v;
		}

		if ( isset( $flat['cf-ray'] ) || isset( $flat['cf-cache-status'] ) ) {
			$detected['Cloudflare'] = $flat['cf-cache-status'] ?? 'Active';
		}
		if ( isset( $flat['x-sucuri-cache'] ) || isset( $flat['x-sucuri-id'] ) ) {
			$detected['Sucuri WAF'] = $flat['x-sucuri-cache'] ?? 'Active';
		}
		if ( isset( $flat['x-amz-cf-id'] ) ) {
			$detected['Amazon CloudFront'] = 'Active';
		}
		if ( isset( $flat['x-fastly-request-id'] ) ) {
			$detected['Fastly'] = 'Active';
		}
		if ( isset( $flat['x-litespeed-cache'] ) ) {
			$detected['LiteSpeed Cache'] = $flat['x-litespeed-cache'];
		}
		if ( isset( $flat['x-cache'] ) ) {
			$detected['Reverse Proxy Cache'] = $flat['x-cache'];
		}

		return $detected;
	}

	/**
	 * Generate simulated core WordPress virtual output for comparison.
	 */
	private static function generate_core_virtual_sample(): string {
		$public = (int) get_option( 'blog_public', 1 );
		if ( '0' === (string) $public ) {
			return "User-agent: *\nDisallow: /\n";
		}

		$output  = "User-agent: *\n";
		$output .= "Disallow: /wp-admin/\n";
		$output .= "Allow: /wp-admin/admin-ajax.php\n";

		if ( function_exists( 'wp_sitemaps_enabled' ) && wp_sitemaps_enabled() ) {
			$output .= "\nSitemap: " . esc_url( home_url( '/wp-sitemap.xml' ) ) . "\n";
		}

		return $output;
	}

	/**
	 * Normalize content for comparison by removing carriage returns and surrounding whitespace.
	 */
	private static function normalize( string $text ): string {
		$clean = str_replace( [ "\r\n", "\r" ], "\n", trim( $text ) );
		// Strip trailing blank lines.
		return trim( $clean );
	}
}
